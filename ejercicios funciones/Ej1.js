// Definimos la función 'sumar' que recibe dos números y devuelve su suma
function sumar(a, b) {
  return a + b;
}

// Ejemplo de uso:
console.log(sumar(3, 5)); // Resultado: 8

// Exportamos la función (opcional, si planeas usarla en otro archivo)
module.exports = sumar;
